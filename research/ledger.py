"""Research ledger: one append-only JSONL file, rendered to LEDGER.md.

Every idea and every evaluation goes in, passes and failures alike. The
number of evaluations an idea has had is what the multiple-testing rule in
``evaluate.py`` reads, so nothing may be deleted or rewritten.

    python -m research.ledger idea --id R001 --title "..." --mechanism "..." --hypothesis "..." --rules "..."
    python -m research.ledger close --id R001 --reason "..."
    python -m research.ledger validate --id R001 --strategy NAME --verdict validated|rejected --reason "..."
    python -m research.ledger render
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LEDGER = ROOT / "ledger.jsonl"
RENDERED = ROOT / "LEDGER.md"


def _commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def append(entry: dict) -> dict:
    entry = {"ts": datetime.now(timezone.utc).isoformat(timespec="seconds"), "commit": _commit(), **entry}
    with LEDGER.open("a") as fh:
        fh.write(json.dumps(entry, sort_keys=True) + "\n")
    return entry


def entries() -> list[dict]:
    if not LEDGER.exists():
        return []
    return [json.loads(line) for line in LEDGER.read_text().splitlines() if line.strip()]


def ideas() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for e in entries():
        if e["kind"] == "idea":
            out[e["id"]] = {**e, "status": "proposed", "evals": defaultdict(int), "best": None, "strategies": set()}
    for e in entries():
        idea = out.get(e.get("id") or e.get("idea"))
        if idea is None:
            continue
        if e["kind"] == "eval":
            idea["evals"][e["period"]] += 1
            idea["strategies"].add(e["strategy"])
            if e["period"] == "build":
                if e["verdict"] == "pass":
                    idea["status"] = "candidate"
                    idea["best"] = e
                elif idea["status"] == "proposed":
                    idea["status"] = "build_fail"
                    if idea["best"] is None or e["metrics"].get("net_pips", -9) > idea["best"]["metrics"].get("net_pips", -9):
                        idea["best"] = e
        elif e["kind"] == "validate":
            idea["status"] = e["verdict"]
            idea["validation"] = e
        elif e["kind"] == "close":
            if idea["status"] not in ("validated", "candidate"):
                idea["status"] = "closed"
            idea["closed"] = e
    return out


def build_evals(idea_id: str) -> int:
    return sum(1 for e in entries() if e["kind"] == "eval" and e.get("idea") == idea_id and e["period"] == "build")


def next_id() -> str:
    nums = [int(e["id"][1:]) for e in entries() if e["kind"] == "idea" and e["id"][1:].isdigit()]
    return f"R{(max(nums) + 1) if nums else 1:03d}"


def render() -> str:
    rows = sorted(ideas().values(), key=lambda i: i["id"])
    lines = [
        "# Research ledger",
        "",
        "Generated by `python -m research.ledger render` from `ledger.jsonl`. Do not edit by hand.",
        "",
        "| id | title | status | build evals | best build net / edge (t) | strategies |",
        "|---|---|---|---:|---|---|",
    ]
    for i in rows:
        b = i["best"]["metrics"] if i["best"] else None
        best = f"{b['net_pips']:+.2f} / {b['edge_pips']:+.2f} ({b['edge_t']:+.1f})" if b else "-"
        lines.append(f"| {i['id']} | {i['title']} | **{i['status']}** | {i['evals'].get('build', 0)} | {best} | "
                     f"{', '.join(sorted(i['strategies'])) or '-'} |")
    counts = defaultdict(int)
    for i in rows:
        counts[i["status"]] += 1
    lines += ["", "Totals: " + (", ".join(f"{k} {v}" for k, v in sorted(counts.items())) or "none yet"), ""]
    lines += ["## Ideas", ""]
    for i in rows:
        lines += [f"### {i['id']}: {i['title']}", "",
                  f"- **Mechanism:** {i.get('mechanism', '')}",
                  f"- **Hypothesis:** {i.get('hypothesis', '')}",
                  f"- **Rules:** {i.get('rules', '')}",
                  f"- **Status:** {i['status']}"]
        if i.get("validation"):
            v = i["validation"]
            lines.append(f"- **Validation ({v['ts'][:10]}):** {v['verdict']}: {v.get('reason', '')}")
        if i.get("closed"):
            lines.append(f"- **Closed ({i['closed']['ts'][:10]}):** {i['closed'].get('reason', '')}")
        lines.append("")
    text = "\n".join(lines)
    RENDERED.write_text(text)
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="research.ledger")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("idea")
    p.add_argument("--id", default=None, help="defaults to the next free R###")
    for f in ("title", "mechanism", "hypothesis", "rules"):
        p.add_argument(f"--{f}", required=True)
    p = sub.add_parser("close")
    p.add_argument("--id", required=True)
    p.add_argument("--reason", required=True)
    p = sub.add_parser("validate")
    p.add_argument("--id", required=True)
    p.add_argument("--strategy", required=True)
    p.add_argument("--verdict", choices=["validated", "rejected"], required=True)
    p.add_argument("--reason", required=True)
    sub.add_parser("render")
    sub.add_parser("next-id")
    a = ap.parse_args(argv)

    known = ideas()
    if a.cmd == "idea":
        idea_id = a.id or next_id()
        if idea_id in known:
            ap.error(f"idea {idea_id} already exists")
        append({"kind": "idea", "id": idea_id, "title": a.title, "mechanism": a.mechanism,
                "hypothesis": a.hypothesis, "rules": a.rules})
        print(idea_id)
    elif a.cmd in ("close", "validate"):
        if a.id not in known:
            ap.error(f"unknown idea {a.id}")
        if a.cmd == "close":
            append({"kind": "close", "id": a.id, "reason": a.reason})
        else:
            append({"kind": "validate", "id": a.id, "strategy": a.strategy, "verdict": a.verdict, "reason": a.reason})
    elif a.cmd == "next-id":
        print(next_id())
        return 0
    render()
    if a.cmd == "render":
        print(RENDERED.read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main())
